
console.log('-------------------Operators Precedence-------------------')
 let res1 = 10 + 5 * 2;
console.log("10 + 5 * 2 =", res1);

let res2 = (10 + 5) * 2;
console.log("(10 + 5) * 2 =", res2);

let res3 = 20 + 10 / 2;
console.log("20 + 10 / 2 =", res3);

let res4 = 10 + 5 > 12;
console.log("10 + 5 > 12 =", res4);

let res5 = true || false && false;
console.log("true || false && false =", res5);

let res6 = (true || false) && false;
console.log("(true || false) && false =", res6);